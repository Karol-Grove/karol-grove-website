  window.getActivePriceCatalog = function() {
    try {
      const cached = localStorage.getItem('kg_prices_local');
      if (cached) {
        const parsed = JSON.parse(cached);
        if (Array.isArray(parsed) && parsed.length > 0) {
          // If stored in legacy composite format, normalize:
          if (parsed[0].price250g !== undefined && parsed[0].packSize === undefined) {
            return defaultCatalog;
          }
          return parsed;
        }
      }
    } catch (e) {
      console.error('Error reading kg_prices_local from storage:', e);
    }
    return defaultCatalog;
  };

